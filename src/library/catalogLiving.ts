import { type Box, type Part, type Spec, line, poly, rect } from './catalogShapes';

/** Sofa with n seats in a 52 × 22 px thumbnail-scale frame, arms 6 px wide (design "thumb/Sofa 3 seat"). */
function sofa(seats: number, w: number): Part[] {
  const px = 52 * (w / 2.2);
  const x0 = 100 - px / 2;
  const cushions = Array.from({ length: seats - 1 }, (_, i) => {
    const x = x0 + 6 + ((px - 12) * (i + 1)) / seats;
    return line(x, 221, x, 230);
  });
  return [
    rect(x0, 218, px, 22, { r: 4 }),
    rect(x0 + 6, 233, px - 12, 7),
    rect(x0, 218, 6, 22, { r: 3 }),
    rect(x0 + px - 6, 218, 6, 22, { r: 3 }),
    ...cushions,
  ];
}

const sofaBox = (w: number): Box => [100 - (52 * (w / 2.2)) / 2, 218, 52 * (w / 2.2), 22];

